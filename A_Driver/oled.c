/* ---- SPI 发送一个字节 ---- */
static void OLED_SPI_Write(unsigned char data)
{
    DL_SPI_transmitDataBlocking8(OLED_SPI_INST, data);
}

/* ---- 写命令 (DC=0, CS↓→发→CS↑) ---- */
static void OLED_WriteCmd(unsigned char cmd)
{
    DL_GPIO_clearPins(OLED_DC_PORT, OLED_DC_PIN);
    DL_GPIO_clearPins(OLED_CS_PORT, OLED_CS_PIN);
    OLED_SPI_Write(cmd);
    DL_GPIO_setPins(OLED_CS_PORT, OLED_CS_PIN);
}

/* ---- 写数据块 (DC=1, CS↓→发→CS↑) ---- */
static void OLED_WriteData(const unsigned char *data, unsigned int len)
{
    DL_GPIO_setPins(OLED_DC_PORT, OLED_DC_PIN);
    DL_GPIO_clearPins(OLED_CS_PORT, OLED_CS_PIN);
    unsigned int i;
    for (i = 0; i < len; i++)
        OLED_SPI_Write(data[i]);
    DL_GPIO_setPins(OLED_CS_PORT, OLED_CS_PIN);
}

static void OLED_WriteCmd2(unsigned char cmd, unsigned char arg)
{
    OLED_WriteCmd(cmd);
    OLED_WriteCmd(arg);
}

/* ---- 帧缓冲: 8 pages × 128 cols = 1024 bytes ---- */
static unsigned char gFramebuf[8][128];

/* ---- 初始化 ---- */
void OLED_Init(void)
{
    /* RES 复位: 低→延时→高 */
    DL_GPIO_clearPins(OLED_RES_PORT, OLED_RES_PIN);
    delay_cycles(32000);
    DL_GPIO_setPins(OLED_RES_PORT, OLED_RES_PIN);
    delay_cycles(320000);
    /* SSD1306 初始化命令序列 */
    OLED_WriteCmd(0xAE);       /* 关闭显示 */
    OLED_WriteCmd2(0xD5, 0x80); /* 时钟分频 */
    OLED_WriteCmd2(0xA8, 0x3F); /* 复用比 64 */
    OLED_WriteCmd2(0xD3, 0x00); /* 显示偏移 0 */
    OLED_WriteCmd(0x40);        /* 起始行 0 */
    OLED_WriteCmd2(0x8D, 0x14); /* 使能电荷泵 */
    OLED_WriteCmd2(0x20, 0x00); /* 水平寻址 */
    OLED_WriteCmd(0xA1);        /* 段重映射 */
    OLED_WriteCmd(0xC8);        /* COM 扫描方向 */
    OLED_WriteCmd2(0xDA, 0x12); /* COM 引脚 */
    OLED_WriteCmd2(0x81, 0xCF); /* 对比度 */
    OLED_WriteCmd2(0xD9, 0xF1); /* 预充电 */
    OLED_WriteCmd2(0xDB, 0x40); /* VCOMH */
    OLED_WriteCmd(0xA4);        /* 正常模式 */
    OLED_WriteCmd(0xA6);        /* 不反色 */
    OLED_WriteCmd(0xAF);        /* 开启显示 */
}

/* ---- 清屏 ---- */
void OLED_Clear(void)
{
    unsigned char p, c;
    for (p = 0; p < 8; p++)
        for (c = 0; c < 128; c++)
            gFramebuf[p][c] = 0;
}

/* ---- 刷新 ---- */
void OLED_Refresh(void)
{
    OLED_WriteCmd(0x21); OLED_WriteCmd(0); OLED_WriteCmd(127);
    OLED_WriteCmd(0x22); OLED_WriteCmd(0); OLED_WriteCmd(7);
    unsigned char p;
    for (p = 0; p < 8; p++)
        OLED_WriteData(gFramebuf[p], 128);
}

/* ---- 写字符串到帧缓冲 (6×8 字体) ---- */
void OLED_ShowString(uint32_t page, uint32_t col, const char *str)
{
    while (*str) {
        if (col > 121) { col = 0; page++; }
        if (page > 7) break;

        unsigned char idx = (unsigned char)*str;
        idx = (idx < 0x20 || idx > 0x7F) ? 0 : idx - 0x20;

        unsigned char i;
        for (i = 0; i < 5; i++)
            gFramebuf[page][col + i] = Font5x7[idx][i];
        gFramebuf[page][col + 5] = 0;  /* 字符间距 */
        col += 6; str++;
    }
}

/* ---- 定位 (保留, 帧缓冲模式下无实际作用) ---- */
void OLED_SetCursor(uint32_t page, uint32_t col) { (void)page; (void)col; }
